import type { CSSProperties } from 'react'
import { BrowserView } from './BrowserView'
import { browserSlotStyle } from '../../shared/browser-slot-style'

/**
 * Браузер СМОНТИРОВАН ВСЕГДА — независимо от того, открыта ли вкладка «Браузер».
 *
 * ЗАЧЕМ (требование №5 исходного ТЗ: вкладка — окно НАБЛЮДЕНИЯ для человека, а не
 * условие работы инструментов; №2: ОДИН браузер, не два). `window.verstakBrowser`
 * ставится в useEffect при монтировании `BrowserView`. Пока вкладку ни разу не
 * открыли — компонент не смонтирован, API нет, и `browser_navigate` падает «вкладка
 * Browser не открыта», хотя агенту уже дали структурное зрение, клик, ввод и
 * ожидание. Павел на живой задаче («открой сайт альфы») получил ровно это: зрение
 * бесполезно, если глаза открываются только руками пользователя.
 *
 * КАК: держим `BrowserView` смонтированным всегда, а когда вкладка не выбрана —
 * прячем через `display:none`. Electron 40 исполняет `loadURL`/`executeJavaScript` в
 * СКРЫТОМ webview (проверено живым смоуком: скрытый и даже скрытый-с-рождения webview
 * навигируется и отдаёт DOM), а при открытии вкладки человек видит РОВНО страницу
 * агента — тот же самый webview, не второй браузер и не пустой экран.
 *
 * `display:contents` в активном состоянии делает обёртку прозрачной для лейаута, так
 * что `.gg-panel` браузера раскладывается ровно как раньше (когда рендерился прямо во
 * вкладке). Безопасность не меняется: SEC-CMD-гейты живут в `browserHandler`
 * (electron), до `window.verstakBrowser` — этот компонент их не касается.
 *
 * ЧЕМ прячется вне своей вкладки — решает `shared/browser-slot-style.ts`, и это НЕ
 * стилистическая мелочь: `display:none` убирал у страницы лейаут-бокс, из-за чего
 * внутри неё вьюпорт был 0×0, кадры не приходили, а IntersectionObserver не срабатывал
 * никогда — SPA-выдача не отрисовывалась вовсе (замер 12.08, P3 кусок 2). Стиль вынесен
 * в shared, потому что его проверяют ДВА разных теста — jsdom-пин и живой смоук на
 * настоящем Electron; копия стиля в смоуке была бы зелёной при сломанном продукте.
 */
export function PersistentBrowser({ active }: { active: boolean }) {
  return (
    <div className="gg-browser-slot" style={browserSlotStyle(active) as CSSProperties}>
      <BrowserView />
    </div>
  )
}
