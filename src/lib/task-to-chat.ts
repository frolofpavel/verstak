/**
 * Задача 4: превратить пункт чеклиста в инструкцию агенту для отправки в чат
 * (через gg-resume-send). Чистая функция — пустой/пробельный пункт даёт пустую
 * строку (кнопка «В работу» тогда ничего не шлёт).
 */
export function formatTaskForChat(text: string): string {
  const t = (text ?? '').trim()
  if (!t) return ''
  return `Возьми в работу задачу из чеклиста и выполни её:\n\n${t}`
}
