/**
 * P3 кусок 3: СРЕД СТАЛО ДВЕ. Контракт выбора среды — один источник для схемы
 * инструмента, хендлера и пинов (§3.1: фикстура обязана совпадать с продовой формой,
 * а расхождение схемы/исполнителя/гейта — уже дефект).
 *
 * ЗАЧЕМ вторая среда, если встроенная работает. Встроенный браузер — ОДНА общая
 * сессия с состоянием человека: его куки, его входы в кабинеты, его ручные действия.
 * Для localhost-разработки и повторяемых прогонов это ровно то, что мешает: прогон
 * зависит от того, куда человек до этого заходил, а ошибки консоли смешаны с его
 * кликами. Изолированная сессия решает три вещи разом — чистое состояние,
 * повторяемость, свои ошибки — и умирает вместе с задачей.
 *
 * ВТОРОГО НАБОРА ИНСТРУМЕНТОВ НЕТ (прямой запрет рамки волны, browser-three-modes §9).
 * Агент работает теми же `browser_*`: имена, аргументы и смысл прежние, различается
 * только СРЕДА исполнения. Она задаётся полем `env` у `browser_navigate` — точки
 * входа, — а дальше ЛИПНЕТ к прогону, пока её не сменят явно или не закроют сессию.
 *
 * ПОЧЕМУ ЛИПНЕТ, а не берётся по умолчанию каждый раз: рамка волны запрещает
 * молчаливую смену среды (§4). Если бы `browser_find` без `env` возвращался во
 * встроенный, модель, работающая в чистой сессии, молча получила бы страницу из
 * ЧУЖОГО браузера с чужими куками — и не узнала бы об этом. Поэтому «без env» значит
 * «там же, где и был», а всякая смена — явная и со следом (поле `mode` в каждом
 * ответе, метка в журнале, запись в ленте).
 */

export type BrowserEnv = 'builtin' | 'isolated'

/** Допустимые значения `env` — ЗАКРЫТЫЙ список (схема инструмента = этот массив). */
export const BROWSER_ENVS: readonly BrowserEnv[] = ['builtin', 'isolated']

/** Среда по умолчанию: встроенный браузер. Вторая среда — только по явному запросу. */
export const DEFAULT_BROWSER_ENV: BrowserEnv = 'builtin'

/** Человеческие подписи сред (рамка волны §7 фаза E: не показывать «webview»/«playwright»). */
export const BROWSER_ENV_LABEL: Record<BrowserEnv, string> = {
  builtin: 'встроенный браузер',
  isolated: 'чистая сессия',
}

/**
 * ПРАВИЛО ВЫБОРА СРЕДЫ — объявлено здесь ОДИН раз и отсюда попадает в описание
 * `browser_navigate` (то есть в контракт, который читает модель). Дублировать текст
 * в описании нельзя: копия разъедется и однажды соврёт (§3.1).
 *
 * ЧЕСТНО О ГРАНИЦАХ ЭТОГО ПРАВИЛА. Первая строка — РАНТАЙМ: дефолт и липкость решает
 * `resolveBrowserEnv`, они проверяемы тестом. Вторая — ПРОСЬБА к модели, и доказать
 * её выполнение тестом нельзя по построению (урок 30.07 с plan-директивой: живая
 * инструкция, которой модель не следует, — семя ложной записи). Классификатор
 * «сама решу за модель по первому сообщению» здесь СТРОГО хуже: код видит один URL,
 * модель — всю задачу («проверь мою правку», «повтори дважды одинаково»).
 */
export const BROWSER_ENV_RULE =
  'По умолчанию работает встроенный браузер (env="builtin") — он же остаётся, если env не указан. ' +
  'Бери env="isolated" (чистая изолированная сессия), когда нужен localhost/dev-сервер, ' +
  'когда сценарий должен быть повторяемым, или когда чужие куки и ручные действия человека ' +
  'исказили бы результат. Чистая сессия НЕ видит входов пользователя в кабинеты — ' +
  'для залогиненных сайтов бери встроенный.'

/** Локальный ли адрес — признак задачи «своя правка / dev-сервер». */
export function isLocalhostUrl(url: string): boolean {
  const raw = String(url ?? '').trim()
  if (!raw) return false
  let host: string
  try {
    host = new URL(/^[a-z][\w+.-]*:\/\//i.test(raw) ? raw : 'http://' + raw).hostname.toLowerCase()
  } catch {
    return false
  }
  if (host === 'localhost' || host.endsWith('.localhost')) return true
  if (host === '::1' || host === '[::1]') return true
  if (host === '0.0.0.0') return true
  return /^127\.\d{1,3}\.\d{1,3}\.\d{1,3}$/.test(host)
}

export type EnvResolution =
  | { ok: true; env: BrowserEnv; switched: boolean }
  | { ok: false; error: string }

/**
 * Какая среда исполняет этот вызов. `requested` — поле `env` из аргументов модели
 * (может отсутствовать), `active` — среда прогона на данный момент.
 *
 * Незнакомое значение — ЧЕСТНАЯ ОШИБКА, а не молчаливый откат в дефолт. Откат здесь
 * был бы худшим видом фолбэка: модель просила изоляцию, получила бы общий браузер с
 * куками человека и не узнала бы об этом (§3.1 про фолбэк без следа).
 */
export function resolveBrowserEnv(requested: unknown, active: BrowserEnv): EnvResolution {
  if (requested === undefined || requested === null || requested === '') {
    return { ok: true, env: active, switched: false }
  }
  const want = String(requested)
  if (!(BROWSER_ENVS as readonly string[]).includes(want)) {
    return {
      ok: false,
      error: `Неизвестная среда браузера «${want}». Допустимо только: ${BROWSER_ENVS.join(', ')} ` +
             `(${BROWSER_ENV_LABEL.builtin} / ${BROWSER_ENV_LABEL.isolated}).`,
    }
  }
  const env = want as BrowserEnv
  return { ok: true, env, switched: env !== active }
}

/**
 * Подсказка «здесь уместнее чистая сессия» — НЕ подмена решения модели, а видимый
 * повод его пересмотреть. Ставится только там, где правило однозначно: localhost
 * открыт во встроенном браузере, который копит состояние по построению.
 */
export function localhostEnvHint(env: BrowserEnv, url: string): string | undefined {
  if (env !== 'builtin' || !isLocalhostUrl(url)) return undefined
  return 'Это локальный адрес. Для повторяемой проверки своей правки бери browser_navigate с env="isolated" — ' +
         'чистую сессию без чужих кук, которая закроется вместе с задачей.'
}

export type UrlNormalization = { ok: true; url: string } | { ok: false; error: string }

/**
 * Привести адрес к виду, пригодному для навигации ИНСТРУМЕНТА.
 *
 * СОЗНАТЕЛЬНОЕ ОТЛИЧИЕ от адресной строки встроенного браузера: там не-URL уезжает
 * в Google (`SEARCH_URL`), и это правильно — поле набирает ЧЕЛОВЕК, и «погода в
 * Барнауле» обязано работать. Здесь адрес приходит от МОДЕЛИ, и молчаливый поисковый
 * запрос вместо навигации — худший исход: изолированная сессия существует ради
 * повторяемости, а «случайно открылась выдача поисковика» её убивает и выглядит как
 * успех. Поэтому не-адрес — честная ошибка.
 *
 * Хвост, названный явно: у встроенного пути своя копия нормализации внутри
 * `BrowserView` (она обслуживает и адресную строку человека). Свести их в одну —
 * отдельная работа, требующая правки встроенного пути, который эта задача трогать
 * не должна.
 */
export function normalizeAgentUrl(input: string): UrlNormalization {
  const trimmed = String(input ?? '').trim()
  if (!trimmed) return { ok: false, error: 'Пустой адрес: укажи URL страницы.' }
  if (/^(https?|file|about):/i.test(trimmed)) return { ok: true, url: trimmed }
  // Голый хост (localhost:5173, example.com/path) — достраиваем схему.
  if (/^(localhost|\[[0-9a-f:]+\]|[\w-]+(\.[\w-]+)+|\d{1,3}(\.\d{1,3}){3})(:\d+)?(\/.*)?$/i.test(trimmed)) {
    return { ok: true, url: 'http://' + trimmed }
  }
  return {
    ok: false,
    error: `«${trimmed}» не похоже на адрес страницы. Здесь нужен URL (например http://localhost:5173 ` +
           'или https://example.com) — поисковый запрос вместо навигации сделал бы прогон невоспроизводимым.',
  }
}
