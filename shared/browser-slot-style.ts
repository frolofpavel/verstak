/**
 * КАК ПРЯЧЕТСЯ встроенный браузер, пока его вкладка не открыта.
 *
 * Живёт в shared/ и является ЕДИНСТВЕННЫМ источником этого решения: тот же модуль
 * импортирует `PersistentBrowser` (renderer), jsdom-пин и живой смоук на настоящем
 * Electron (`scripts/smoke-browser-spa.mjs`). Иначе смоук мерил бы КОПИЮ стиля, а не
 * продовое решение, и был бы зелёным при сломанном продукте (CLAUDE.md §3.1: тест,
 * чья фикстура не совпадает с продовой формой, не защищает ничего).
 *
 * ЗАМЕР 12.08 (P3 кусок 2, живой Electron 40), воспроизводится командой
 * `npm run smoke:browser-spa` — три состояния ОДНОГО webview на локальной SPA-фикстуре:
 *
 *   состояние слота                     вьюпорт     rAF/с   IntersectionObserver  выдача
 *   вкладка открыта (display:contents)  1184×150    146     сработал              3
 *   вкладка закрыта (ЭТОТ стиль)        1184×835      4     сработал              3
 *   вкладка закрыта (display:none)         0×0        0     МОЛЧИТ                0
 *
 * Частота кадров в закрытом состоянии ниже (страница перекрыта интерфейсом, Chromium
 * рисует её редко) — и это НОРМА: важен не темп, а сам факт кадров и настоящий размер
 * окна. Ноль кадров при нулевом вьюпорте — отказ, четыре кадра в секунду — работа.
 *
 * `display:none` УБИРАЕТ У СТРАНИЦЫ ЛЕЙАУТ-БОКС, поэтому внутри неё `innerWidth` и
 * `innerHeight` равны нулю. Для SPA это не «страница спрятана», а «окно нулевого
 * размера»: ленивая подгрузка по IntersectionObserver не срабатывает никогда,
 * виртуализованные списки не рендерят ни одной строки, а всё, что ждёт кадра
 * (requestAnimationFrame), не дожидается его вовсе. Инструменты при этом исправны и
 * отвечают честно — снимок показывает ровно то, что на странице есть, то есть
 * пустоту. Отсюда наблюдение Павла «поиск выполнился, а выдачи нет».
 *
 * ЛЕЧЕНИЕ — не таймер и не «подождать подольше»: страница обязана иметь НАСТОЯЩИЙ
 * вьюпорт и получать кадры, оставаясь невидимой для человека. Поэтому вне своей
 * вкладки слот не удаляется из лейаута, а выносится из потока (`position:fixed`),
 * растягивается на окно (`inset:0` — вьюпорт как у открытой вкладки), делается
 * прозрачным (`opacity:0`), уходит ПОД интерфейс (`zIndex:-1`) и перестаёт ловить
 * мышь (`pointerEvents:none`). Человек по-прежнему не видит браузер вне его вкладки —
 * контракт прежний, изменился только способ его выполнения.
 *
 * ЦЕНА, названная честно: страница вне вкладки больше не троттлится, то есть живёт
 * как обычная фоновая вкладка браузера. Это и есть смысл «браузер работает, пока ты
 * на него не смотришь»; молчаливая деградация до нулевого вьюпорта дороже (§3.1 про
 * фолбэк, который прячет дефект, который компенсирует).
 *
 * БЕЗОПАСНОСТЬ НЕ ЗАТРОНУТА: это только CSS слота в renderer. Гейты режима, правила
 * URL и запреты навигации живут в main (`browserHandler`, `will-attach-webview`,
 * SEC-CMD-*) и этим модулем не касаются.
 */

/** Плоский стиль слота — общий для React (CSSProperties) и для живого смоука. */
export interface BrowserSlotStyle {
  display?: string
  position?: string
  inset?: string
  opacity?: string
  zIndex?: string
  pointerEvents?: string
}

/** Вкладка открыта: обёртка прозрачна для лейаута, `.gg-panel` раскладывается как раньше. */
export const BROWSER_SLOT_ACTIVE: BrowserSlotStyle = { display: 'contents' }

/**
 * Вкладка закрыта: невидим человеку и не мешает интерфейсу, но ЖИВОЙ — с настоящим
 * вьюпортом и кадрами. `display` намеренно НЕ 'none' (см. замер в шапке).
 */
export const BROWSER_SLOT_HIDDEN: BrowserSlotStyle = {
  // `grid` (а не блок): единственный потомок — панель браузера — растягивается по
  // ОБЕИМ осям сама. Без этого у панели высота по содержимому, webview получал ~150px
  // вместо высоты окна, и страница жила в узкой щели (замер живого приложения 12.08).
  display: 'grid',
  position: 'fixed',
  inset: '0',
  opacity: '0',
  zIndex: '-1',
  pointerEvents: 'none',
}

export function browserSlotStyle(active: boolean): BrowserSlotStyle {
  return active ? BROWSER_SLOT_ACTIVE : BROWSER_SLOT_HIDDEN
}

/** Тот же стиль строкой — для `element.style.cssText` в живом смоуке. */
export function browserSlotCssText(active: boolean): string {
  const s = browserSlotStyle(active)
  const kebab = (k: string) => k.replace(/[A-Z]/g, m => '-' + m.toLowerCase())
  return Object.entries(s).map(([k, v]) => `${kebab(k)}:${v}`).join(';')
}
