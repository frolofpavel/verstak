/**
 * Дефолт агентного режима — ОДНА точка на main и renderer (V5, волна 2.6.0).
 *
 * ЧТО МЕНЯЕТСЯ. Дефолт `ask` → `auto`: Verstak перестаёт спрашивать на рутинных
 * правках и командах. Claude Code перешёл на авто по умолчанию; решение Павла
 * 11.08 — «здесь должно быть так же».
 *
 * ПОЧЕМУ ЭТО БЕЗОПАСНО — проверено по коду, а не предположено. В
 * `permission-rules.resolveDecision` проверка `classifyResponsibleAction` стоит
 * ВЫШЕ режима, выше per-tool автоподтверждения и выше allow-правил (единственное
 * исключение записано явно — `bypass`). Публикация, отправка, удаление, выдача
 * прав и платёж останавливают прогон в `auto` ровно так же, как в `ask`.
 *
 * ГЛАВНОЕ В РЕАЛИЗАЦИИ — КАК ХРАНИТСЯ «ЧЕЛОВЕК ВЫБИРАЛ САМ». Не сравнением с
 * дефолтом, а ФАКТОМ ЗАПИСИ: ключ `agent_mode` появляется в настройках только
 * когда пользователь переключил режим (пикер или Shift+Tab), а иначе его нет
 * вовсе. Поэтому «нет значения» = новый пользователь → дефолт, «есть значение» =
 * осознанный выбор → уважаем его каким бы он ни был.
 *
 * Сравнение с дефолтом здесь было бы дефектом, и он назван, чтобы никто не
 * «упростил» обратно: пользователь, который СОЗНАТЕЛЬНО выбрал `ask`, при
 * сравнении «сохранённое === старый дефолт → значит не выбирал» получил бы
 * `auto` после обновления — то есть молча лишился бы подтверждений, ради
 * которых и выбирал режим.
 */

export type AgentModeId = 'ask' | 'accept-edits' | 'plan' | 'auto' | 'bypass'

export const AGENT_MODE_IDS: readonly AgentModeId[] = ['ask', 'accept-edits', 'plan', 'auto', 'bypass']

/**
 * Режим нового пользователя. Смена этой константы затрагивает ТОЛЬКО тех, у кого
 * значения в настройках нет: у выбравшего вручную запись уже лежит и побеждает.
 */
export const DEFAULT_AGENT_MODE: AgentModeId = 'auto'

export function isAgentModeId(v: unknown): v is AgentModeId {
  return typeof v === 'string' && (AGENT_MODE_IDS as readonly string[]).includes(v)
}

/**
 * Режим по сохранённому значению.
 *
 * `null`/`undefined`/пусто — выбора НЕ БЫЛО → дефолт продукта.
 * Валидная строка — выбор человека → он и применяется.
 * Мусор (неизвестный режим) — тоже дефолт: это не выбор, а порча значения.
 *
 * `fallback` задаётся явно там, где у контекста свой дефолт (справочный чат
 * работает в своём режиме и к продуктовому дефолту отношения не имеет).
 */
export function resolveAgentMode(
  stored: string | null | undefined,
  fallback: AgentModeId = DEFAULT_AGENT_MODE,
): AgentModeId {
  return isAgentModeId(stored) ? stored : fallback
}

/** Выбирал ли человек режим сам (в этом scope). Факт записи, не сравнение.
 *
 *  ЗАДУМАНО, НО НЕ ПОДКЛЮЧЕНО, и это объявляется (§1.4 ревизии, 15.08): вопрос
 *  «человек выбрал режим сам или это дефолт продукта» сегодня не задаёт никто —
 *  функция живёт своим тестом. Отличать эти два состояния нужно ровно там, где
 *  дефолт будет меняться: перещёлкивать молча того, кто выбрал сам, нельзя (тот
 *  же принцип, что у полярности флагов в runtime-flag-policy). Оставлена как
 *  готовый ответ на этот вопрос, а не как забытый код. */
export function hasExplicitAgentMode(stored: string | null | undefined): boolean {
  return isAgentModeId(stored)
}
