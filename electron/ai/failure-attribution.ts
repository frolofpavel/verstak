/**
 * Почему упало: условие прогона или всё-таки код.
 *
 * Зачем (01.09). При падении команды модели летел сырой вывод и общее «почини». Она
 * начинала менять код — даже когда код ни при чём: приложение держало нативный модуль,
 * файл был занят, прогон оборвался. Это стоит не токенов, а нескольких ходов вслепую,
 * и хуже того — правок в исправном коде.
 *
 * ГЛАВНОЕ: сигнатуры здесь НЕ придуманы и не взяты у конкурентов. Они выписаны из
 * CLAUDE.md §3.1 — раздела, который в этом проекте нажит потерянными днями. Там это
 * записано как правило ДЛЯ ЧЕЛОВЕКА («счёт падений — не вердикт; вердикт — это
 * СООБЩЕНИЯ плюс УСЛОВИЯ прогона»), а у агента такого правила не было. Модуль просто
 * отдаёт агенту то, что команда уже знает.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО: попытки чинить самому. Классификатор только
 * НАЗЫВАЕТ причину и говорит, чего НЕ делать. Решение остаётся за моделью — она видит
 * задачу целиком, а этот модуль видит один вывод (см. §3.1 про «решим в коде вместо
 * модели»: код видит меньше модели, и назначать ему решение — ухудшение).
 *
 * ОСТОРОЖНО С ЛОЖНОЙ УВЕРЕННОСТЬЮ. Неверная атрибуция опаснее её отсутствия: сказать
 * «код верен, дело в окружении» там, где код сломан, — значит увести от настоящей
 * причины авторитетным тоном. Поэтому сигнатуры узкие, а по умолчанию — null
 * (ничего не добавляем).
 */

export type FailureCategory =
  /** Нативный модуль собран под другой ABI: приложение открыто и держит .node. */
  | 'abi-lock'
  /** Файл/каталог занят другим процессом: EBUSY/EPERM/EACCES на записи или удалении. */
  | 'resource-busy'
  /** Порт занят. */
  | 'port-busy'
  /** Команда не найдена: не установлен бинарник, не тот PATH. */
  | 'command-missing'
  /** Прогон оборвался, не собрав набор: вердикта нет ни зелёного, ни красного. */
  | 'run-truncated'
  /** Тест не уложился в лимит: признак нагрузки, а не утверждения. */
  | 'timeout'

export interface AttributedFailure {
  category: FailureCategory
  /** Короткая формулировка причины — идёт заголовком к выводу. */
  headline: string
  /** Что делать И ЧЕГО НЕ ДЕЛАТЬ. Формулируется как совет, не как приказ. */
  action: string
}

/** Сколько падений по одной подписи считаем «массовыми» (признак условия, не кода). */
const MASS_FAILURES = 20

/**
 * Разбирает вывод упавшей команды. null — причина не опознана; тогда ничего не
 * добавляем, пусть модель разбирается сама. Молчание честнее догадки.
 */
export function attributeFailure(output: string, exitCode: number | null): AttributedFailure | null {
  if (!output) return null
  const text = output.slice(-20_000) // хвост: причина почти всегда в конце

  // 1. ABI нативного модуля. В этом проекте означает ровно одно: открыто приложение,
  //    оно держит better_sqlite3.node. Код при этом не менялся (CLAUDE.md §3.1).
  if (/NODE_MODULE_VERSION|was compiled against a different Node\.js version/i.test(text)) {
    const many = countMatches(text, /NODE_MODULE_VERSION/gi) >= 3
    return {
      category: 'abi-lock',
      headline: many
        ? 'Массовые падения по ABI нативного модуля — это УСЛОВИЕ ПРОГОНА, а не регрессия'
        : 'Нативный модуль собран под другой ABI',
      action:
        'Скорее всего открыто приложение Verstak — оно держит better_sqlite3.node. ' +
        'НЕ правь код и не «чини» тесты: они не при чём. Закрой приложение и повтори прогон ' +
        '(pretest сам пересоберёт модуль под нужный ABI).',
    }
  }

  // 2. Занятый файл. Сегодняшний живой случай: dist:win падает EBUSY на
  //    v8_context_snapshot.bin, если запущена собранная копия приложения.
  if (/\bEBUSY\b|resource busy or locked|EPERM|EACCES/i.test(text)) {
    return {
      category: 'resource-busy',
      headline: 'Файл или каталог занят другим процессом',
      action:
        'Это условие окружения, а не ошибка в коде. Найди процесс, который держит файл ' +
        '(часто — запущенная копия приложения или редактор), закрой его и повтори. ' +
        'Логику не меняй.',
    }
  }

  if (/\bEADDRINUSE\b|address already in use/i.test(text)) {
    return {
      category: 'port-busy',
      headline: 'Порт занят',
      action: 'Освободи порт или возьми другой. Код менять не нужно.',
    }
  }

  if (/is not recognized as an internal or external command|command not found|\bENOENT\b.*spawn/i.test(text)) {
    return {
      category: 'command-missing',
      headline: 'Команда не найдена',
      action:
        'Бинарника нет в PATH или он не установлен. Проверь установку и имя команды; ' +
        'правка исходников тут не поможет.',
    }
  }

  // 3. Оборванный прогон. §3.1: набор МЕНЬШЕ эталона — не вердикт, а оборванный
  //    запуск; трактовать его ни зелёным, ни красным нельзя.
  if (/Test Files\s+\d+\s+failed/i.test(text) && /\bECONNRESET\b|heap out of memory|FATAL ERROR|worker (?:exited|terminated)/i.test(text)) {
    return {
      category: 'run-truncated',
      headline: 'Прогон оборвался, не собрав набор — это НЕ вердикт о коде',
      action:
        'Часть файлов не дошла до сбора (память, воркеры). Результат нельзя считать ни ' +
        'зелёным, ни красным. Сначала восстанови полноту: снизь параллелизм ' +
        '(--maxWorkers=4), разгрузи машину — и только потом суди о падениях.',
    }
  }

  // 4. Таймаут. Признак нагрузки; утверждение теста при этом не проверялось.
  if (/Test timed out in \d+ms|Hook timed out in \d+ms/i.test(text)) {
    const many = countMatches(text, /timed out in \d+ms/gi) >= 3
    return {
      category: 'timeout',
      headline: many ? 'Массовые таймауты — признак нагрузки, а не утверждений' : 'Тест не уложился в лимит',
      action:
        'Таймаут означает, что утверждение НЕ проверялось: это про условия прогона. ' +
        'Прежде чем править тест или код — измерь, что именно долгое, и снизь параллелизм. ' +
        'Поднимать лимит имеет смысл только после замера.',
    }
  }

  // Массовые падения без опознанной подписи — тоже повод усомниться в «регрессии»,
  // но своей причины у нас нет. Говорим ровно это и не выдумываем диагноз.
  const failed = matchCount(text, /(\d+)\s+failed/i)
  if (failed !== null && failed >= MASS_FAILURES && exitCode !== 0) {
    return {
      category: 'run-truncated',
      headline: `Падений сразу ${failed} — прежде чем считать это регрессией, проверь условия прогона`,
      action:
        'Столько падений разом чаще означает условие (открытое приложение, недособранный ' +
        'набор, чужая правка в рабочем дереве), чем поломку логики. Посмотри СООБЩЕНИЯ ' +
        'нескольких падений: разные причины — условие; одно и то же утверждение — код.',
    }
  }

  return null
}

function countMatches(text: string, re: RegExp): number {
  return (text.match(re) ?? []).length
}

function matchCount(text: string, re: RegExp): number | null {
  const m = text.match(re)
  return m ? Number(m[1]) : null
}

/** Готовая шапка для вывода упавшей команды. Пусто — причина не опознана. */
export function formatAttribution(f: AttributedFailure | null): string {
  if (!f) return ''
  return `⚠ ${f.headline}\n${f.action}\n`
}
