/**
 * Что уже решено и что уже отвергнуто — в контекст нового чата.
 *
 * Зачем (31.08). Verstak давно пишет Decision Record: решение, почему, возражения,
 * риски и — самое ценное — ОТВЕРГНУТЫЕ АЛЬТЕРНАТИВЫ. Человеку это показывается
 * (панель «Решения», карточка прогона). Агенту НЕ показывалось никогда: `context-pack`
 * о решениях не знал. Поэтому назавтра агент начинал с чистого листа и предлагал ровно
 * то, что вчера уже разобрали и отклонили.
 *
 * ПОЧЕМУ ИМЕННО ОТВЕРГНУТОЕ. Конкуренты (по обзору 31.08) инжектят цель и веху —
 * «где мы находимся». Это полезно, но повторяемо кем угодно. Ценность, которую трудно
 * скопировать, лежит в другом: память о ТУПИКАХ. Знание «сюда уже ходили, не сработало
 * по такой-то причине» экономит не токены, а прогон целиком — и его нельзя вывести из
 * кода, оно накапливается только работой.
 *
 * БЮДЖЕТ. Блок идёт в КАЖДЫЙ первый ход, поэтому он маленький и жёстко ограничен:
 * несколько последних решений, короткие строки. Раздутый блок вытеснит собой то, ради
 * чего затевался, и станет дороже пользы.
 *
 * ЧЕСТНОСТЬ. Если решений нет — секции нет вовсе. Пустой заголовок «Решения: —»
 * приучает модель пролистывать блок и обесценивает его в тот день, когда он наполнится.
 */

export interface DecisionForContext {
  title: string
  finalDecision: string | null
  why: string | null
  alternativesRejected: string[]
  createdAt: number
}

/** Сколько решений максимум попадёт в контекст. */
export const MAX_DECISIONS = 5
/** Предел длины одной строки — заголовка, решения, отвергнутой альтернативы. */
export const MAX_LINE = 160

function short(s: string | null | undefined, limit = MAX_LINE): string {
  const t = String(s ?? '').replace(/\s+/g, ' ').trim()
  return t.length > limit ? t.slice(0, limit - 1) + '…' : t
}

function stamp(ts: number): string {
  const d = new Date(ts)
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${pad(d.getDate())}.${pad(d.getMonth() + 1)}`
}

/**
 * Собирает блок для system-контекста. Пустая строка — секции быть не должно.
 * Решения передаются УЖЕ отсортированными по свежести (самое новое первым).
 */
export function buildDecisionsBlock(decisions: DecisionForContext[]): string {
  const list = decisions.slice(0, MAX_DECISIONS).filter(d => short(d.title))
  if (list.length === 0) return ''

  const lines: string[] = []
  for (const d of list) {
    const head = `- ${stamp(d.createdAt)} ${short(d.title)}`
    const what = short(d.finalDecision)
    lines.push(what ? `${head} → ${what}` : head)

    const why = short(d.why, 120)
    if (why) lines.push(`  почему: ${why}`)

    // Ради этого блок и существует: не повторять уже разобранный тупик.
    const rejected = d.alternativesRejected.map(a => short(a, 100)).filter(Boolean).slice(0, 3)
    if (rejected.length > 0) lines.push(`  УЖЕ ОТВЕРГНУТО: ${rejected.join(' · ')}`)
  }

  // Про пометку отвергнутого говорим ТОЛЬКО если она в блоке есть. Инструкция про
  // маркер, которого ниже не встретится, — шум: модель учится пролистывать шапку.
  const hasRejected = lines.some(l => l.includes('УЖЕ ОТВЕРГНУТО'))
  const preamble = hasRejected
    ? [
        'Это записи прошлых сессий. Не предлагай заново то, что помечено «УЖЕ ОТВЕРГНУТО»,',
        'без новой причины — по этим путям уже ходили. Если считаешь, что решение устарело,',
        'скажи об этом прямо и объясни, что изменилось.',
      ]
    : [
        'Это записи прошлых сессий. Учитывай их и не переигрывай молча: если считаешь,',
        'что решение устарело, скажи об этом прямо и объясни, что изменилось.',
      ]

  return ['## Что уже решено в этом проекте', '', ...preamble, '', ...lines].join('\n')
}
