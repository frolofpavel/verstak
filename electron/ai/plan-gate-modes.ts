/**
 * Матрица режимов агента для гейта согласования плана (ТЗ VSK-TASK-FLOW-A1, §5).
 *
 * ЧТО ЭТОТ МОДУЛЬ РЕШАЕТ И ЧЕГО НЕ РЕШАЕТ. Он отвечает ровно на один вопрос:
 * «применим ли гейт согласования» — то есть КТО спрашивает (режим, контекст,
 * глубина делегирования). Что именно в плане (запись, ответственное действие,
 * риск) по-прежнему решает порог `plan-threshold.ts`, а права на запись —
 * `mode-policy.decide()`. Три разных вопроса, три разных модуля; смешивать их в
 * один было бы удобно и неверно.
 *
 * ПЕРЕВОРОТ, КОТОРЫЙ ЗДЕСЬ ПРОИСХОДИТ. До §5 карточка появлялась ровно в одном
 * режиме — `plan`, и только при включённой настройке. ТЗ требует обратного:
 * в `plan` кнопки «Утвердить» быть НЕ должно (в этом режиме выполнение запрещено
 * всегда), зато карточка обязана появляться в `ask` и `accept-edits`, где гейта
 * не было вовсе.
 *
 * ПОРЯДОК ВЕТВЕЙ ЗНАЧИМ, и первая — не про режим. В фазе `plan` Outcome-пайплайна
 * режим прогона ПРИНУДИТЕЛЬНО ставится в 'plan' ещё до старта (ipc/ai.ts:465),
 * а кнопка approve — единственное, что двигает пайплайн на фазу execute. Если
 * судить только по режиму, правило «в plan карточки нет» убило бы пайплайн
 * целиком. Поэтому Outcome-фаза — своя ось, и проверяется она ПЕРВОЙ.
 *
 * ПОЧЕМУ НАСТРОЙКА — РУБИЛЬНИК ЧАТ-КОНТЕКСТА. Тумблер «Ждать одобрения плана»
 * (Настройки → Политики) с A3 §2.1 (30.07) ВКЛЮЧЁН по умолчанию (прежде был
 * выключен; прежняя запись «выключен по умолчанию» пережила свою правду и снята
 * здесь — §3.1). Матрица чат-контекста применяется, когда тумблер включён; при
 * выключенном (человек снял его сам) поведение чат-контекста БАЙТ В БАЙТ
 * прежнее, а §5 включается вместе с ним.
 */
import type { AgentMode } from './mode-policy'

export interface PlanGateInput {
  /** Режим ПРОГОНА на текущий ход (ctx.agentMode — снимок мутабельного holder'а). */
  agentMode: AgentMode
  /** ctx.outcome?.phase. Строка, а не тип из ipc/ — чтобы ai/ не зависел от ipc/. */
  outcomePhase?: string | null
  /** Настройка `plan_approval_gate` === 'true'. Рубильник чат-контекста. */
  planApprovalSetting?: boolean
  /** ctx.delegationDepth: 0 — главный агент, ≥1 — субагент. */
  delegationDepth?: number
}

/**
 * Применим ли гейт согласования плана. Дальше слово за порогом §4.2.
 *
 * Субагент гейта не получает СОЗНАТЕЛЬНО: `setAgentMode` доезжает до него копией
 * контекста, но замыкание мутирует holder РОДИТЕЛЬСКОГО прогона. Субагент,
 * показавший карточку, понизил бы права родителя и удержал бы чужой чекпойнт.
 * Сегодня `create_plan` не входит ни в один роль-набор, то есть комбинация
 * достижима только через самодельный agent-файл с `tools: ['create_plan']` —
 * это защита на будущее, а не лечение живого сценария.
 */
export function planGateApplies(input: PlanGateInput): boolean {
  // Ось 1 — Outcome-пайплайн. Проверяется первой и режимом не отменяется.
  if (input.outcomePhase === 'plan') return true
  if ((input.delegationDepth ?? 0) > 0) return false
  // Рубильник чат-контекста. Выключен → сегодняшнее поведение целиком.
  if (input.planApprovalSetting !== true) return false

  switch (input.agentMode) {
    // Карточка по порогу §4.2 — то, чего в этих режимах не было вовсе.
    case 'ask':
    case 'accept-edits':
      return true
    // ПЕРЕВОРОТ §5: в режиме планирования согласовывать нечего — выполнение
    // запрещено всегда (`decide(*, 'plan') === 'block'`, и правила permissions
    // это не ослабляют). Карточки нет → и кнопки «Утвердить» нет.
    case 'plan':
      return false
    // План автоутверждается целиком: карточки нет, порог даже не спрашиваем.
    // Здесь же сидит unattended-прогон (scheduled ставит 'auto') — жёсткое false
    // и есть та защита, на которой стоит §6.
    // bypass — по ТЗ дословно: как сегодня, без нового гейта.
    case 'auto':
    case 'bypass':
      return false
  }
}
