/**
 * Хвост stderr дочернего CLI, пригодный для показа ЧЕЛОВЕКУ (29.07).
 *
 * ЗАЧЕМ. Четыре CLI-провайдера кладут в пользовательскую ошибку сырой
 * `stderrBuffer` — часто это единственное, что объясняет, почему бинарь не
 * запустился, поэтому убирать его нельзя. Но stderr дочернего процесса содержит
 * строки запуска с флагами, куски окружения и пути, то есть ровно тот материал,
 * ради которого существует `secret-scanner`. До этой правки он шёл мимо него.
 *
 * ПОЧЕМУ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ `scanText` НА КАЖДОМ ИЗ ПЯТИ МЕСТ. Пять
 * одинаковых выражений в четырёх файлах — это пять мест, где следующий человек
 * может забыть про очистку, и ни одного места, где об этом написано. Здесь же
 * зафиксирован и порядок: СНАЧАЛА чистим, ПОТОМ режем.
 *
 * ПОРЯДОК ВАЖЕН И ПРОВЕРЕН ПИНОМ. Редакция УДЛИНЯЕТ текст (`--token abc` →
 * `--token [REDACTED:cli-secret]`), поэтому «отрезать 400, потом почистить»
 * оставляет риск разрезать секрет пополам ровно на границе — половина ключа
 * уходит человеку, а сканер её уже не узнаёт, потому что паттерн не совпал.
 * Чистим весь буфер, режем очищенный.
 */
import { scanText } from './secret-scanner'

/** Сколько символов хвоста показываем человеку. */
export const CLI_STDERR_LIMIT = 400

/**
 * Очищенный хвост stderr для пользовательской ошибки.
 * Пустой буфер даёт пустую строку — вызывающий сам решает, показывать ли префикс.
 */
export function safeStderrTail(stderr: string | null | undefined, limit: number = CLI_STDERR_LIMIT): string {
  if (!stderr) return ''
  return scanText(stderr).redacted.slice(0, limit)
}
