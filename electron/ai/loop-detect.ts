/**
 * Д4 (приёмка браузера 10.08) — подпись БЕЗАРГУМЕНТНОГО вызова для детектора
 * зацикливания.
 *
 * ЧТО БЫЛО СЛОМАНО. Детектор (`runner-api`, `signatureCounts`, LOOP_THRESHOLD=3)
 * считает подпись как «имя + аргументы». У `browser_snapshot` параметров нет
 * вовсе, поэтому его подпись КОНСТАНТНА: третий снимок за прогон блокировался
 * всегда — даже если это была другая страница после навигации. В живой приёмке
 * заблокированным оказался ровно тот инструмент, который вёл к решению.
 *
 * ПРАВИЛО. У безаргументного вызова единственный различающий признак — то, что
 * он НАБЛЮДАЕТ. Поэтому вместо «сколько раз позвали» считаем «сколько раз подряд
 * увидели ОДНО И ТО ЖЕ»: снимок изменившейся страницы обнуляет счёт, снимок
 * неизменной — наращивает. Порог остаётся общий (LOOP_THRESHOLD): третий вызов,
 * которому предшествовали два одинаковых наблюдения, блокируется — ровно как
 * блокируется третий одинаковый вызов с аргументами. Симметрия намеренная:
 * человек видит одну и ту же ноту про зацикливание.
 *
 * ГРАНИЦА С V2-4 (`progress.ts`). Тот смотрит на ЗНАНИЕ прогона целиком (новый
 * ли факт за ход) и лечит застой подсказкой сменить стратегию. Этот механизм
 * смотрит на ОДИН инструмент и не даёт ему исполниться. Общий у них только
 * приём нормализации волатильного (время, длительности) — он и взят из V2-4
 * одной функцией, чтобы «снимок с таймером на странице» не выглядел вечно новым.
 *
 * ВТОРАЯ ПОЛОВИНА ПРАВИЛА — ДЕЙСТВИЕ ОБНУЛЯЕТ СЧЁТ. Без неё оставался ложный
 * блок ровно того же рода, что чинится: два одинаковых снимка, затем навигация —
 * и третий снимок (уже другой страницы) не исполнялся бы, потому что о смене
 * контекста рантайм узнаёт только из результата, которого ещё нет. Поэтому
 * намеренное действие агента (навигация, клик, ввод, нажатие клавиши, запись,
 * команда) сбрасывает наблюдения: мир изменился по его же воле, смотреть заново
 * законно. Набор — не литералы в условии, а перечень поверх MUTATING_BROWSER_TOOLS,
 * чтобы следующий мутирующий инструмент попадал сюда сам.
 */
import { observationDigest } from './progress'
import { MUTATING_BROWSER_TOOLS } from './mode-policy'
import { MUTATING_TOOL_NAMES } from './review-gate'

/** Наблюдения безаргументных инструментов за прогон: имя → что видели и сколько раз подряд. */
export interface ObservationState {
  last: Map<string, string>
  streak: Map<string, number>
}

export function createObservationState(): ObservationState {
  return { last: new Map(), streak: new Map() }
}

/**
 * Безаргументный ли вызов. Именно у таких подпись «имя + аргументы» вырождается
 * в константу; вызовы с аргументами идут прежним путём и поведения не меняют.
 */
export function hasNoArgs(args: unknown): boolean {
  if (args == null) return true
  if (typeof args !== 'object' || Array.isArray(args)) return false
  return Object.keys(args as Record<string, unknown>).length === 0
}

/**
 * Блокировать ли этот безаргументный вызов: предыдущие `threshold - 1` наблюдений
 * подряд были одинаковыми, значит следующий такой же вызов — топтание на месте.
 */
export function shouldBlockArgless(state: ObservationState, name: string, threshold: number): boolean {
  return (state.streak.get(name) ?? 0) >= Math.max(1, threshold - 1)
}

/**
 * Учесть, что инструмент увидел. Совпало с прошлым разом — счёт растёт; увидел
 * новое (другая страница, изменившийся вывод) — счёт сбрасывается в единицу.
 * Ошибка исполнения — тоже наблюдение: повторять падающий вызов так же бессмысленно.
 */
export function recordObservation(
  state: ObservationState,
  name: string,
  outcome: { result?: unknown; error?: string },
): void {
  const key = observationDigest(outcome.error ? `!${outcome.error}` : outcome.result)
  const same = state.last.get(name) === key
  state.last.set(name, key)
  state.streak.set(name, same ? (state.streak.get(name) ?? 0) + 1 : 1)
}

/**
 * Меняет ли этот вызов то, что увидят безаргументные наблюдатели. Навигация
 * стоит отдельной строкой: гейту режимов она не мутация (в `plan` смотреть
 * страницы можно), а наблюдаемое меняет сильнее всего.
 */
export function changesObservation(name: string): boolean {
  return name === 'browser_navigate'
    || name === 'run_command'
    || MUTATING_BROWSER_TOOLS.includes(name)
    || MUTATING_TOOL_NAMES.has(name)
}

/** Агент совершил действие — прежние наблюдения устарели, счёт начинается заново. */
export function noteContextChange(state: ObservationState): void {
  state.last.clear()
  state.streak.clear()
}
