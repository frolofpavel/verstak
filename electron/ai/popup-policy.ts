/**
 * Решение о попапе из webview (SEC-CMD-08).
 *
 * ЧТО ЗА ДВЕРЬ. Страница в браузере может открыть новое окно (`target=_blank`,
 * `window.open`). Глухой запрет ломал бы обычные ссылки, поэтому main
 * перенаправлял http(s)-попап в тот же webview — но БЕЗ единой проверки правил.
 * То есть рядом с гейтованной навигацией (SEC-CMD-07) стояла негейтованная
 * дверь: модель кликает по ссылке с `target=_blank` (а клик вне `plan` не
 * гейтован), страница открывает окно, main грузит любой URL молча.
 *
 * ЕДИНЫЙ ИСТОЧНИК, А НЕ ВТОРОЙ ПАРАЛЛЕЛЬНЫЙ. Решение принимает тот же
 * `applyPermissionRules`, что судит `browser_navigate`, и по тому же имени
 * инструмента — значит правило пользователя `browser_navigate(**logout**)`
 * действует на обе двери сразу, а не только на ту, про которую он думал.
 *
 * ЧЕСТНАЯ ГРАНИЦА, И ОНА ВЫНУЖДЕННАЯ. Полностью «та же проверка» здесь
 * невозможна по устройству Electron: `setWindowOpenHandler` СИНХРОНЕН — он
 * обязан вернуть вердикт немедленно, `await` в этой точке не существует.
 * Поэтому:
 *  · режим агента (`plan`/`ask`/…) сюда не применяется: попап — событие
 *    страницы, а не вызов инструмента, у него нет ни прогона, ни sendId;
 *  · `ask`-правило означает ОТКАЗ, а не вопрос: спросить человека неоткуда.
 *    Тихо грузить в этом случае нельзя — человек написал «спрашивай меня», и
 *    молчаливая загрузка была бы прямым нарушением его же правила.
 * Обе оговорки объявлены пинами, а не спрятаны в комментарий.
 */

import { applyPermissionRules, type CompiledPermissionRules } from './permission-rules'

/** Имя, под которым судится попап. То же, что у обычной навигации, — намеренно:
 *  одно правило пользователя закрывает обе двери. */
export const POPUP_TOOL_NAME = 'browser_navigate'

export interface PopupVerdict {
  /** Грузить ли URL в тот же webview. */
  allow: boolean
  /** Причина отказа — человеку в лог, не модели. */
  reason?: string
}

/**
 * Пускать ли попап. Схема проверяется первой: не-http(s) (`javascript:`,
 * `file:`, `data:`) не грузится никогда — у него нет легитимного применения в
 * попапе, и это не вопрос вкуса пользователя.
 */
export function decidePopupNavigation(url: string, rules: CompiledPermissionRules | undefined): PopupVerdict {
  const raw = typeof url === 'string' ? url.trim() : ''
  if (!/^https?:\/\//i.test(raw)) {
    return { allow: false, reason: `попап с не-http(s) схемой заблокирован: ${raw.slice(0, 120)}` }
  }
  const rule = applyPermissionRules(POPUP_TOOL_NAME, raw, rules)
  if (rule?.decision === 'deny') {
    return { allow: false, reason: `попап заблокирован правилом permissions: deny "${rule.rule.raw}"` }
  }
  if (rule?.decision === 'ask') {
    // Спросить синхронно нельзя — значит отказ, а не тихая загрузка.
    return {
      allow: false,
      reason: `попап отклонён: правило "${rule.rule.raw}" требует подтверждения, ` +
        'а всплывающее окно открывается без диалога. Открой адрес обычной навигацией, там вопрос будет задан.'
    }
  }
  return { allow: true }
}
