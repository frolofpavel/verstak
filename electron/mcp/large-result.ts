/**
 * Большой ответ MCP-сервера не должен уезжать в контекст модели целиком.
 *
 * Зачем (29.08). В каталог добавлен рекламный и торговый стек: Метрика с отчётами,
 * Wildberries с выгрузкой товаров, Директ со списком кампаний. Такой ответ — десятки и
 * сотни килобайт, и до сих пор он шёл модели ЦЕЛИКОМ: `JSON.stringify(result)` без
 * единого ограничения. Один вызов способен съесть окно и деньги, а человек не поймёт,
 * за что заплатил.
 *
 * Решение подсмотрено у Antigravity (август 2026): крупный ответ сохраняется файлом, а
 * в переписку идёт ссылка. Здесь то же самое, но в конвенциях Verstak: файл ложится в
 * `.verstak/artifacts/{дата}/`, как остальные артефакты, а модель получает НАЧАЛО
 * ответа плюс путь — чтобы могла прочитать нужное место обычным read_file, а не
 * тащить всё в контекст.
 *
 * Порог согласован с уже принятым в проекте: SSH-коннектор режет вывод по 64 КБ. Здесь
 * меньше — 16 КБ: вывод команды человек читает целиком, а ответ API почти всегда
 * структура, из которой нужна часть.
 *
 * СЕКРЕТЫ. Редакция выполняется ДО разделения, над полным текстом: иначе ключ,
 * попавший в хвост, уехал бы в файл нетронутым. Файл — тоже выход наружу.
 */

export const MCP_RESULT_INLINE_LIMIT = 16 * 1024

export interface LargeResultSplit {
  /** Что уйдёт модели в результате инструмента. */
  inline: string
  /** Полный текст для записи в файл; null — резать не понадобилось. */
  overflow: string | null
}

/**
 * Делит уже отредактированный текст ответа на то, что уйдёт модели, и то, что
 * сохраняется файлом. `filePath` подставляется в подсказку, если резать пришлось.
 */
export function splitLargeMcpResult(redacted: string, filePath: string | null): LargeResultSplit {
  if (redacted.length <= MCP_RESULT_INLINE_LIMIT) {
    return { inline: redacted, overflow: null }
  }
  const head = redacted.slice(0, MCP_RESULT_INLINE_LIMIT)
  const kb = Math.round(redacted.length / 1024)
  // Без пути файл записать не удалось — честно говорим, что остаток потерян, а не
  // делаем вид, что его можно дочитать. Молчаливая обрезка хуже: модель уверена, что
  // видела всё, и строит вывод на половине данных.
  const tail = filePath
    ? `\n\n…ответ обрезан: показано ${Math.round(MCP_RESULT_INLINE_LIMIT / 1024)} КБ из ${kb} КБ.\nПолный ответ сохранён: ${filePath}\nЧитай нужный фрагмент через read_file, не тащи файл целиком.`
    : `\n\n…ответ обрезан: показано ${Math.round(MCP_RESULT_INLINE_LIMIT / 1024)} КБ из ${kb} КБ. Сохранить остаток в файл не удалось — данных ниже этой границы у тебя НЕТ.`
  return { inline: head + tail, overflow: redacted }
}

/** Имя файла для сохранённого ответа: инструмент + отметка времени вызывающего. */
export function largeResultFileName(toolName: string, stamp: number): string {
  const safe = toolName.replace(/[^a-zA-Z0-9_.-]/g, '_').slice(0, 60) || 'mcp'
  return `mcp-${safe}-${stamp}.txt`
}
