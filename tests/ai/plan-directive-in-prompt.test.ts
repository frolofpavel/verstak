// A3: директива «многошаговое исследование → план» доезжает до промпта.
//
// ЖИВОЙ ДЕФЕКТ (прогон Павла 30.07): цикл планов включён по умолчанию, но на
// читающих задачах — «аудит сайта», «посмотри рекламу» — план не появлялся,
// потому что модель его не СОЗДАВАЛА. Раздел «Планы» пуст (0 планов) — значит
// это не потеря карточки, а отсутствие create_plan. Причина найдена по коду:
// шаг PLAN велел показывать план при >5 шагов / >3 файлов / архитектуре, а аудит
// меняет ноль файлов и под порог не попадал. Описание самого инструмента
// (tools.ts) при этом РАЗРЕШАЛО план при 3+ шагах — то есть тексты противоречили,
// и строгий порог шага PLAN побеждал. Директива не «ещё одно разрешение», а
// СНЯТИЕ противоречия.
//
// ЧЕСТНО О ГРАНИЦАХ ЭТОГО ПИНА. Он стережёт от СЛУЧАЙНОГО УДАЛЕНИЯ строки из
// собранного промпта — и только. Он НЕ может утверждать, что модель директиве
// следует: это просьба к модели, а не рантайм-гейт. Единственное доказательство
// работы — живой прогон Павла на читающей задаче. Зелёный пин здесь ≠ приёмка.
import { describe, it, expect } from 'vitest'
import { composeSystemPrompt } from '../../electron/ai/compose-prompt'
import { SYSTEM_LAYER_VERSION } from '../../electron/ai/system-layer'

const prompt = () => composeSystemPrompt({ path: null, content: '' }).system

describe('директива плана на исследовании — в собранном промпте', () => {
  it('промпт называет многошаговое исследование поводом вызвать create_plan', () => {
    const p = prompt()
    expect(p, 'директива исчезла из промпта — цель A3 §2.2 недостижима').toMatch(/create_plan/)
    expect(p.toLowerCase(), 'не назван повод: исследование/аудит/несколько источников')
      .toMatch(/investigation|audit|several (files|sources)/)
  })

  // ОБЯЗАТЕЛЬНОЕ уточнение постановщика: читающий план НЕ останавливает работу.
  // Модель читает шаг PLAN целиком, а он начинается с «wait for confirmation» —
  // без явного «не жди» она перенесёт ожидание и на исследовательский план, и
  // человек получит остановку там, где одобрять нечего.
  it('промпт ЯВНО говорит, что читающий план не ждёт одобрения', () => {
    expect(prompt().toLowerCase(), '«не жди» выводится из контекста, а не сказано словами')
      .toMatch(/informational|do not wait|without waiting|keep working/)
  })

  // Одиночный lookup под план НЕ попадает — иначе «план на всё», от чего Павел
  // отказался. Проверяем, что граница названа в тексте.
  it('промпт называет и обратную границу: одиночный lookup плана не требует', () => {
    expect(prompt().toLowerCase()).toMatch(/single (lookup|file|question)|one (file|folder|question)/)
  })

  // Версия протокола сдвинута — иначе строка «1.3.1» переживёт свою правду:
  // содержимое изменилось, а номер утверждает прежнее (правило §3.1).
  it('версия system-layer сдвинута вместе с изменением текста', () => {
    expect(SYSTEM_LAYER_VERSION, 'версия не сдвинута — номер врёт о содержимом').not.toBe('1.3.1')
  })
})
