// ЗАДАЧА 1, дефект (b) (04.08): карточка пустого прерванного ответа НЕ должна
// выдумывать причину. Живой отказ: человек переключался между чатами/вкладками,
// НЕ закрывая приложение, а карточка утверждала «приложение было закрыто до
// сохранения видимого ответа. Запуск не удалось восстановить автоматически».
//
// Это §3.1 в чистом виде: сообщение УТВЕРЖДАЕТ причину, которой рендер знать не
// может. Он видит ровно одно наблюдаемое: у ассистент-сообщения нет сохранённого
// текста, и оно не стримится. Из этого не следует ни «приложение закрыто», ни
// «запуск не восстановить» — это домыслы, и на custom-openai они оказались просто
// ложью. Карточка обязана говорить известное (сохранённого ответа нет + можно
// повторить) и не называть непроверенную причину.
//
// Красный до фикста: detail содержит «приложение было закрыто».
import { describe, it, expect } from 'vitest'
import { buildInterruptedAnswerProgress } from '../../src/components/chat/ChatStreamMessages'

describe('buildInterruptedAnswerProgress — честная карточка прерванного ответа', () => {
  const [entry] = buildInterruptedAnswerProgress(1_700_000_000_000, 'DeepSeek')

  it('не утверждает закрытие приложения — рендер этого не знает', () => {
    expect(entry.detail).not.toContain('приложение было закрыто')
  })

  it('не утверждает невозможность восстановления как факт', () => {
    expect(entry.detail).not.toContain('не удалось восстановить')
  })

  it('говорит известное: сохранённого ответа нет + можно повторить', () => {
    const text = `${entry.title} ${entry.detail}`.toLowerCase()
    expect(text).toContain('не сохран')
    expect(text).toContain('повтор')
  })

  it('остаётся ошибкой в потоке и подставляет метку провайдера', () => {
    expect(entry.status).toBe('error')
    expect(entry.phase).toBe('final')
    expect(entry.detail).toContain('DeepSeek')
    expect(entry.timestamp).toBe(1_700_000_000_000)
  })
})
