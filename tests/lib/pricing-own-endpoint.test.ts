// C8 (13.08): свой endpoint — деньги не выдумываются.
//
// Замер 12.08 («cost-контроллер на custom-openai считает мимо») разобран по коду.
// Найдено расхождение слоёв, доказуемое без доступа к чужому endpoint'у:
//
//  · main (electron/ai/cost-guard.ts) держит ZERO_COST_PROVIDERS = {ollama,
//    custom-openai} и НЕ копит на них стоимость — «свой endpoint без известного
//    тарифа», решение осознанное и записанное;
//  · renderer (src/lib/pricing.ts) про этот набор не знал и считал такие прогоны
//    по ПУБЛИЧНОЙ таблице цен. Достаточно назвать модель своего прокси знакомым
//    именем (`gpt-4o` — обычное дело для OpenAI-совместимого прокси), и человеку
//    показывались доллары по тарифу OpenAI за чужой сервер, пока страж лимита
//    считал те же токены бесплатными.
//
// Это ровно тот класс, ради которого таблицу PRICES уже переселили в shared
// (см. шапку shared/contracts/pricing.ts: «экран показывал $0, а страж копил
// деньги»). Здесь закрыта вторая половина той же пары.
//
// ЧТО ИМЕННО ПОКАЗЫВАТЬ. Экран приведён к ответу, который main УЖЕ даёт: $0 при
// pricingKnown=1 (cost-guard, proof-pack, trial-estimate, agent_run_usage — все
// четыре места согласованы). Так снимается выдуманное число и НЕ заводится третий
// ответ: «—» на экране при $0 в журнале расхода было бы новым расхождением.
//
// Открытый вопрос ПРОДУКТА (не кода) вынесен штабу: считать свой endpoint
// «заведомо бесплатным» или «тариф неизвестен». Второе честнее по духу правила
// разбивки, но меняет смысл сразу в четырёх местах main и в журнале — это решение
// Павла, а не правка мимоходом.
import { describe, it, expect } from 'vitest'
import { estimateCost, costBreakdown } from '../../src/lib/pricing'
import { ZERO_COST_PROVIDERS } from '../../electron/ai/cost-guard'
import { OWN_ENDPOINT_PROVIDERS } from '../../shared/contracts/pricing'

describe('C8: провайдер со своим endpoint', () => {
  it('ПИН: custom-openai с моделью из публичной таблицы → не выдуманные деньги', () => {
    // gpt-4o есть в PRICES: до правки экран считал чужой прокси по тарифу OpenAI
    // и показывал $12.50 там, где страж лимита считал те же токены бесплатными.
    const cost = estimateCost('custom-openai', 'gpt-4o', 1_000_000, 1_000_000, 0)

    expect(cost.usd, 'экран показывает деньги по чужому тарифу за свой endpoint').toBe('$0.00')
    expect(cost.cents, 'копейки утекли в пороги подсветки жёлтый/красный').toBe(0)
  })

  it('ПИН: разбивка объясняет причину, а не молчит прочерком', () => {
    const text = costBreakdown('custom-openai', 'gpt-4o', 1000, 1000, 0)

    expect(text).toMatch(/тариф|endpoint|неизвест/i)
    expect(text, 'токены человек всё равно должен видеть').toContain('1000')
  })

  it('ПИН: ollama — тот же разбор (локальный inference, публичной цены у него нет)', () => {
    expect(estimateCost('ollama', 'gpt-4o', 1_000_000, 0, 0).usd).toBe('$0.00')
  })

  it('АНТИ-ДРЕЙФ: набор своих endpoint-ов ОДИН у экрана и у стража лимита', () => {
    // Раньше набор жил только в main, и экран про него не знал. Сравниваем
    // содержимое, а не факт импорта: иначе пин зелен и при разошедшихся копиях.
    expect([...ZERO_COST_PROVIDERS].sort()).toEqual([...OWN_ENDPOINT_PROVIDERS].sort())
  })

  it('КОНТРОЛЬ: обычный провайдер с той же моделью деньги считает по-прежнему', () => {
    // Без этого кейса пины выше зелены и у экрана, который не считает НИЧЕГО.
    const cost = estimateCost('openai', 'gpt-4o', 1_000_000, 1_000_000, 0)

    expect(cost.usd).toBe('$12.50')   // 2.5 input + 10 output за 1M каждый
    expect(cost.cents).toBe(1250)
  })

  it('КОНТРОЛЬ: CLI-провайдеры по-прежнему отдают null (подписка), а не «—»', () => {
    expect(estimateCost('claude-cli', 'sonnet', 1000, 1000, 0).usd).toBeNull()
  })
})
