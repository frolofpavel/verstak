import { describe, it, expect } from 'vitest'
import { MCP_CATALOG } from '../../electron/mcp/catalog'

// Каталог 29.08 пополнен рекламным и торговым стеком. Записи в нём неоднородны по
// последствиям: Метрика только читает, а Яндекс Директ создаёт и меняет кампании и
// ставки — то есть влияет на РАСХОД РЕКЛАМНОГО БЮДЖЕТА. Человек выбирает сервер по
// карточке в один клик, и если карточка молчит о такой разнице, он узнает о ней по
// счёту.
//
// Пауза перед ответственным действием в продукте есть и не ослабляется — но она про
// отдельный вызов. Здесь стережётся другое: честность ВЫБОРА при подключении.
//
// Список ведётся руками: определить «умеет ли сервер писать» из кода каталога нельзя,
// это свойство чужого сервера. Добавляешь пишущий сервер — добавь id сюда.
const WRITES = ['yandex-direct']

const WARNING_WORDS = /меняет|создаёт|изменяет|расход|списан|платеж|оплат/i

describe('каталог MCP: пишущие серверы предупреждают', () => {
  it('запись, которая меняет данные или тратит деньги, говорит об этом в описании', () => {
    for (const id of WRITES) {
      const entry = MCP_CATALOG.find(e => e.id === id)
      expect(entry, `в каталоге нет записи ${id}`).toBeTruthy()
      expect(entry!.description, `описание ${id} не предупреждает о последствиях`).toMatch(WARNING_WORDS)
    }
  })

  it('у пишущего сервера есть безопасный режим на виду, если сервер его поддерживает', () => {
    // У Директа это песочница: без неё знакомство с сервером идёт на боевом кабинете.
    const direct = MCP_CATALOG.find(e => e.id === 'yandex-direct')!
    const sandbox = direct.env.find(f => /SANDBOX/i.test(f.key))
    expect(sandbox, 'поле песочницы не вынесено в карточку').toBeTruthy()
    expect(sandbox!.required).toBe(false)
    expect(sandbox!.hint ?? '', 'подсказка не объясняет, зачем песочница').toMatch(/не тратить|тестов/i)
  })

  // КОНТРОЛЬНЫЙ КЕЙС: без него оба утверждения зелены и тогда, когда читающие записи
  // тоже увешаны словами про расход — «предупреждение есть» перестало бы что-то
  // отличать, а человек снова не увидел бы разницы.
  it('читающие записи НЕ пугают понапрасну — предупреждение отличает, а не украшает', () => {
    const metrika = MCP_CATALOG.find(e => e.id === 'yandex-metrika')!
    expect(metrika.description).not.toMatch(WARNING_WORDS)
    expect(metrika.description, 'у читающего сервера не сказано, что он только читает').toMatch(/чтени|только читает/i)
  })

  it('новые записи ссылаются на источник — карточку можно проверить', () => {
    for (const id of ['yandex-metrika', 'yandex-direct', 'bitrix24', 'wildberries', 'dadata']) {
      const e = MCP_CATALOG.find(x => x.id === id)
      expect(e, `нет записи ${id}`).toBeTruthy()
      expect(e!.docsUrl ?? '', `у ${id} нет ссылки на источник`).toMatch(/^https:\/\//)
    }
  })
})
